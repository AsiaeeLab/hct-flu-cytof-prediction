#!/usr/bin/env python3
"""Write the supplementary tables for the composite endpoint, simpler scores and
per-cohort directions. Every number is read from the analysis outputs of the
E12 scripts; nothing is typed by hand. Each table is new in this revision, so its
content is wrapped in \\redrev{} (red in the review copy)."""
from pathlib import Path
import math
import os
import re
import pandas as pd

root = Path('/home/amir/repo/flu-cellular-prediction')
FLU_ROOT = Path(os.environ.get('FLU_RESULTS_ROOT',
                               '/fast/datasets/flu_cellular_prediction/timing_corrected_2026-09-06'))
fast = FLU_ROOT / 'post_hoc_5000'
tabdir = root / 'paper/tables'


def sgn(x):
    return ('$+$' if x >= 0 else '$-$') + f'{abs(x):.3f}'


def num(x, d=1):
    s = f'{x:.{d}f}'
    return s.replace('-', '$-$')


def p_fmt(p, n_boot=None):
    """Two-sided bootstrap p with a floor of 1/B reported as '<0.001'."""
    if p < 0.001:
        return '$<$0.001'
    return f'{p:.3f}'


# ---------------------------------------------------------------------------
# Composite endpoint: ladder comparisons and score-group tests
# ---------------------------------------------------------------------------
