#!/usr/bin/env python3
"""Supplementary table: direction of the populations stably selected in the pooled
composite model (selected in at least 50% of 200 recipient-bootstrap refits of
the composite M4 on the shared atlas), with their selection frequency and
standardized coefficient of the composite M3 refitted in each cohort (E16-02).
Writes paper/tables/cohort_signs.tex."""
import os, re
import pandas as pd
R = os.environ['FLU_RESULTS_ROOT'] + '/post_hoc_5000/composite_main/'
imp = pd.read_csv(R + 'composite_importance.csv')
pooled = imp[(imp.is_cluster) & (imp.sel >= 0.5)].copy()
pooled['cid'] = pooled.cid.astype(int)
sel = pd.read_csv(R + 'per_cohort_selection.csv')
sel = sel[sel.feature.str.startswith('cluster_')].copy(); sel['cid'] = sel.feature.str.replace('cluster_', '').astype(int)
ann = pd.read_csv(os.environ['FLU_ANN_FILE'])
d = pooled.merge(sel, on='cid').merge(ann[['cluster_id', 'annotation']], left_on='cid', right_on='cluster_id')
d = d.sort_values('imp', ascending=False)
sgn = lambda x: ('$+$' if x >= 0 else '$-$') + f'{abs(x):.3f}'
def nm(s):
    s = s.replace('CD38hi', 'CD38-high').replace('\u2212', '$^-$')
    return re.sub(r'\++', lambda m: '$^{' + m.group(0) + '}$', s)
rows = [f"{r.cid} & {nm(r.annotation)} & {sgn(r.imp)} & {100*r.freq_Children:.0f} & {100*r.freq_Adults:.0f} & "
        f"{sgn(r.imp_Children)} & {sgn(r.imp_Adults)} \\\\" for r in d.itertuples()]
same = sum((d.imp_Children > 0) == (d.imp_Adults > 0))
tex = r'''% Generated by experiments/E16-05-cohort-signs-table.py
\begin{table}[p]
\centering
\caption{\textbf{Direction of the stably selected populations in each cohort.}
Populations selected in at least 50\% of 200 recipient-bootstrap refits of the
pooled composite model with titers, clinical factors and immune-cell
composition (M4). Pooled coefficient: bootstrap-averaged coefficient times the
population's standard deviation. Per cohort: the composite model with titers and
composition (M3) was refitted in 200 recipient-bootstrap samples of each cohort
with one penalty strength for both cohorts; selection is the percentage of refits
with a nonzero coefficient, and the coefficient is averaged over refits and
multiplied by the population's standard deviation in that cohort. Positive values
indicate a higher predicted composite log fold-rise. ''' + f'{same} of {len(d)}' + r''' populations had the same
direction in both cohorts.}
\label{tab:cohort_signs}
\footnotesize
\begin{tabular}{rp{4.4cm}rrrrr}
\toprule
 & & Pooled & \multicolumn{2}{c}{Selection (\%)} & \multicolumn{2}{c}{Coefficient} \\
Population & Label & coefficient & Children & Adults & Children & Adults \\
\midrule
''' + '\n'.join(rows) + r'''
\bottomrule
\end{tabular}
\end{table}
'''
open('paper/tables/cohort_signs.tex', 'w').write(tex)
print(d[['cid', 'annotation', 'imp', 'freq_Children', 'freq_Adults', 'imp_Children', 'imp_Adults']].to_string())
print('same direction:', same, 'of', len(d))
