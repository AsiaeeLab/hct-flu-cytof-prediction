#!/usr/bin/env python3
"""Supplementary table of the three-antigen (multitask) models, which are a
sensitivity analysis now that the composite response is the primary outcome.
Reads the aggregated MSE summary and the recipient-bootstrap comparisons of the
first-season composite-selected folds. Writes paper/tables/multitask.tex."""
import os
import pandas as pd
R = os.environ['FLU_RESULTS_ROOT']
mse = pd.read_csv(R + '/per_fold_atlas_5000/aggregated/E2_mse_summary.csv')
mse = mse[mse.model.str.endswith('_en')].pivot(index='model', columns='virus', values='mse')
ci = pd.read_csv(R + '/post_hoc_5000/recipient_bootstrap/E3_recipient_boot.csv')
order = ['M1_to_M3', 'M1_to_M4', 'M2_to_M4', 'M2_to_M3', 'M1_to_M2', 'M3_to_M4']
label = {'M1_to_M3': 'M1$\\to$M3 (composition over titers)', 'M1_to_M4': 'M1$\\to$M4 (full over titers)',
         'M2_to_M4': 'M2$\\to$M4 (composition over clinical)', 'M2_to_M3': 'M2$\\to$M3 (composition vs clinical)',
         'M1_to_M2': 'M1$\\to$M2 (clinical over titers)', 'M3_to_M4': 'M3$\\to$M4 (clinical on top of composition)'}
num = lambda x, d=1: f'{x:.{d}f}'.replace('-', '$-$')
pf = lambda p: '$<$0.001' if p < 0.001 else f'{p:.3f}'
rows_a = [f"{m[:2]} & {num(mse.loc[m + '_en', 'overall'], 3)} & {num(mse.loc[m + '_en', 'h1n1'], 3)} & "
          f"{num(mse.loc[m + '_en', 'h3n2'], 3)} & {num(mse.loc[m + '_en', 'bvic'], 3)} \\\\"
          for m in ['M1', 'M2', 'M3', 'M4']]
rows_b = []
for c in order:
    d = ci[(ci.comparison == c)].set_index('scope')
    cells = []
    for sc in ['overall', 'h1n1', 'h3n2', 'bvic']:
        r = d.loc[sc]
        cells.append(f"{num(r.delta_pct)} ({pf(r.p_two_sided)})")
    rows_b.append(f"{label[c]} & " + ' & '.join(cells) + ' \\\\')
o = ci[ci.scope == 'overall'].set_index('comparison')
tex = r'''% Generated by experiments/E16-06-multitask-table.py
\begin{table}[p]
\centering
\caption{\textbf{Models for the three antigens separately.} The primary analysis
predicts the composite response (Table~\ref{tab:primary}); here the three antigen
log fold-rises are predicted jointly by a multitask elastic net, which selects one
feature set for all three. The three measurements of a recipient stay in the same
cross-validation fold and are resampled together. \textbf{A.}~Mean squared error
of the out-of-fold predictions. \textbf{B.}~Percent reduction in mean squared
error between models, overall and by antigen, with two-sided $p$ from a
recipient-level paired bootstrap ($B = 2{,}000$). The overall intervals are
''' + f"{num(o.loc['M1_to_M3','delta_pct'])}\\% ({num(o.loc['M1_to_M3','ci_low_pct'])} to {num(o.loc['M1_to_M3','ci_high_pct'])}) for M1$\\to$M3 and {num(o.loc['M2_to_M4','delta_pct'])}\\% ({num(o.loc['M2_to_M4','ci_low_pct'])} to {num(o.loc['M2_to_M4','ci_high_pct'])}) for M2$\\to$M4." + r'''}
\label{tab:multitask}
\footnotesize
\textbf{A. Prediction error by model}\\[0.3em]
\begin{tabular}{lcccc}
\toprule
Model & Overall & H1N1 & H3N2 & B/Victoria \\
\midrule
''' + '\n'.join(rows_a) + r'''
\bottomrule
\end{tabular}

\vspace{1em}
\textbf{B. Percent reduction in error, $p$ in parentheses}\\[0.3em]
\begin{tabular}{lcccc}
\toprule
Comparison & Overall & H1N1 & H3N2 & B/Victoria \\
\midrule
''' + '\n'.join(rows_b) + r'''
\bottomrule
\end{tabular}
\end{table}
'''
open('paper/tables/multitask.tex', 'w').write(tex)
print(mse.round(3).to_string())
print(ci[ci.scope == 'overall'][['comparison', 'delta_pct', 'ci_low_pct', 'ci_high_pct', 'p_two_sided']].round(2).to_string())
